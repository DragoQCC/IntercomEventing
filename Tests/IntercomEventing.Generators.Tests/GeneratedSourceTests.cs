    [Test]
    public async Task KeywordNamespaceAndTypeNames_AreEscapedInSourceButNotInFileNames()
    {
        //ToDisplayString writes @class, and '@' is not allowed in a file name; AddSource would throw and drop every file
        var run = GeneratorHarness.Run("""
            using IntercomEventing;

            namespace @class.Events;

            public partial class @event
            {
                [IntercomEvent]
                private readonly IntercomEvent<int> _changed = new();

                [IntercomEvent]
                private static readonly IntercomEvent<int> s_ticked = new();
            }
            """);

        var hintNames = run.GeneratedSources.Select(source => source.HintName).OrderBy(hintName => hintName, StringComparer.Ordinal).ToArray();
        var generatedText = string.Join("\n", run.GeneratedSources.Select(source => source.SourceText.ToString()));
        await Assert.That(hintNames.Length).IsEqualTo(2);
        await Assert.That(hintNames[0]).StartsWith("class.Events.event._changed.");
        await Assert.That(hintNames[1]).StartsWith("class.Events.event.s_ticked.");
        await Assert.That(generatedText).Contains("namespace @class.Events\n{\n    partial class @event\n    {\n");
        await Assert.That(generatedText).Contains("global::@class.Events.@event.s_ticked).Raised += value;");
        await Assert.That(run.DescribeCompilationProblems()).IsEqualTo(string.Empty);
    }

