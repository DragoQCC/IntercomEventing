    [Test]
    public async Task NestedTypeAndNamespaceWithTheSameDottedName_GetDistinctFileNames()
    {
        //A.B+C and A.B.C read the same; equal hint names would make AddSource throw and drop every file, Elsewhere's too.
        //Declaring both is CS0101, but the generator must leave that error to the compiler
        var run = GeneratorHarness.Run("""
            using IntercomEventing;

            namespace A
            {
                public partial class B
                {
                    public partial class C
                    {
                        [IntercomEvent]
                        private readonly IntercomEvent<int> _changed = new();
                    }
                }
            }

            namespace A.B
            {
                public partial class C
                {
                    [IntercomEvent]
                    private readonly IntercomEvent<int> _changed = new();
                }
            }

            namespace Elsewhere
            {
                public partial class Unrelated
                {
                    [IntercomEvent]
                    private readonly IntercomEvent<int> _opened = new();
                }
            }
            """);

        var hintNames = run.GeneratedSources.Select(source => source.HintName).ToArray();
        var distinctIgnoringCase = hintNames.Distinct(StringComparer.OrdinalIgnoreCase).Count();
        await Assert.That(hintNames.Length).IsEqualTo(3);
        await Assert.That(distinctIgnoringCase).IsEqualTo(3);
        await Assert.That(hintNames.Count(hintName => hintName.StartsWith("A.B.C._changed.", StringComparison.Ordinal))).IsEqualTo(2);
        await Assert.That(hintNames.Any(hintName => hintName.StartsWith("Elsewhere.Unrelated._opened.", StringComparison.Ordinal))).IsTrue();
    }

