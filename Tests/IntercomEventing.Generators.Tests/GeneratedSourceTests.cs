        var generatedTree = run.RunResult.GeneratedTrees.Single();
        var diagnostics = run.OutputCompilation.GetDiagnostics();
        var diagnosticsInGeneratedFile = diagnostics.Where(diagnostic => diagnostic.Location.SourceTree == generatedTree).ToArray();
        var subscriberDiagnosticIds = diagnostics
            .Where(diagnostic => diagnostic.Location.SourceTree?.FilePath == "Subscriber.cs")
            .Where(diagnostic => diagnostic.Severity >= DiagnosticSeverity.Warning)
            .Select(diagnostic => diagnostic.Id)
            .Distinct()
            .ToArray();
        await Assert.That(forwardedAttributeCount).IsEqualTo(2);
        await Assert.That(DiagnosticFormatting.Describe(diagnosticsInGeneratedFile)).IsEqualTo(string.Empty);
        await Assert.That(subscriberDiagnosticIds).IsEquivalentTo(new[] { diagnosticIdAtTheSubscriber });
    }

