    [Test]
    public async Task InstanceField_GeneratesForwardingEventAndViewProperty()
    {
        var run = GeneratorHarness.Run("""
            using IntercomEventing;

            namespace Sample.Users;

            public sealed record UserCreated(string Name);

            public sealed partial class UserRegistry
            {
                [IntercomEvent]
                private readonly IntercomEvent<UserCreated> _userCreated = new();
            }
            """);

        var expectedSource = $$"""
            // <auto-generated/>
            #nullable enable

            namespace Sample.Users
            {
                partial class UserRegistry
                {
                    /// <summary>
                    /// Occurs each time this event is raised: <c>+=</c> subscribes a handler and <c>-=</c> removes the most recently added
                    /// equal handler.
                    /// </summary>
                    /// <remarks>
                    /// Forwards to the field's <see cref="global::IntercomEventing.IntercomEventBase{TCall}.Raised"/>: <c>+=</c> gives no
                    /// subscription handle and takes no hooks, and <c>-=</c> starts the <c>OnUnsubscribed</c> hook of the subscription it
                    /// removes, if it has one. Subscribe through <see cref="UserCreatedEvent"/> for a disposable handle, hooks or a
                    /// per-subscription exception handler.
                    /// </remarks>
                    /// <example>
                    /// <code>
                    /// userRegistry.UserCreated += OnUserCreatedAsync;
                    /// userRegistry.UserCreated -= OnUserCreatedAsync;
                    /// </code>
                    /// </example>
                    [global::System.CodeDom.Compiler.GeneratedCode("IntercomEventing.Generators", "{{GeneratorVersion}}")]
                    public event global::System.Func<global::IntercomEventing.EventCall<global::Sample.Users.UserCreated>, global::System.Threading.Tasks.Task> UserCreated
                    {
                        add
                        {
                            ((global::IntercomEventing.IntercomEventBase<global::IntercomEventing.EventCall<global::Sample.Users.UserCreated>>)this._userCreated).Raised += value;
                        }
                        remove
                        {
                            ((global::IntercomEventing.IntercomEventBase<global::IntercomEventing.EventCall<global::Sample.Users.UserCreated>>)this._userCreated).Raised -= value;
                        }
                    }

                    /// <summary>
                    /// The subscribe-only view of the <see cref="UserCreated"/> event, for subscriptions that need a handle,
                    /// lifecycle hooks or a per-subscription exception handler.
                    /// </summary>
                    /// <remarks>
                    /// <c>Subscribe</c> returns a handle that removes the handler when disposed, and <c>SubscribeAsync</c> also runs
                    /// <c>OnSubscribed</c> and <c>OnUnsubscribed</c> hooks. The view has no member that raises or disposes the event,
                    /// but it is the event object itself, typed as its subscribe-only interface.
                    /// </remarks>
                    /// <example>
                    /// <code>
                    /// using var subscription = userRegistry.UserCreatedEvent.Subscribe(call => Console.WriteLine(call.Metadata.RaisedAt));
                    /// </code>
                    /// </example>
                    [global::System.CodeDom.Compiler.GeneratedCode("IntercomEventing.Generators", "{{GeneratorVersion}}")]
                    public global::IntercomEventing.IIntercomEvent<global::IntercomEventing.EventCall<global::Sample.Users.UserCreated>> UserCreatedEvent => this._userCreated;
                }
            }

            """;

        await Assert.That(run.SingleGeneratedText).IsEqualTo(expectedSource.ReplaceLineEndings("\n"));
        await Assert.That(run.GeneratedSources[0].HintName).StartsWith("Sample.Users.UserRegistry._userCreated.");
        await Assert.That(run.GeneratedSources[0].HintName).EndsWith(".g.cs");
        await Assert.That(run.DescribeReportedDiagnostics()).IsEqualTo(string.Empty);
        await Assert.That(run.DescribeCompilationProblems()).IsEqualTo(string.Empty);
    }

